"""ReportLab A4 report: banner, styled sections, Pandas grid, 'Page X of Y' footer."""
from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path
from xml.sax.saxutils import escape

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.pdfgen import canvas
from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

NAVY = colors.HexColor("#14284B")
ACCENT = colors.HexColor("#2E86C1")
ZEBRA = colors.HexColor("#EEF3F9")
FOOTER_NOTE = ("Generated by the Multi-Agent Market Research Crew. "
               "For information only; not financial advice.")


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas so every footer can say 'Page X of Y'."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_pages: list[dict] = []

    def showPage(self):
        self._saved_pages.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved_pages)
        for state in self._saved_pages:
            self.__dict__.update(state)
            self._footer(total)
            super().showPage()
        super().save()

    def _footer(self, total: int):
        width, _ = A4
        self.setStrokeColor(ACCENT)
        self.setLineWidth(0.6)
        self.line(2 * cm, 1.7 * cm, width - 2 * cm, 1.7 * cm)
        self.setFont("Helvetica", 7.5)
        self.setFillColor(colors.grey)
        self.drawString(2 * cm, 1.2 * cm, FOOTER_NOTE)
        self.drawRightString(width - 2 * cm, 1.2 * cm, f"Page {self._pageNumber} of {total}")


def _clean(text: str) -> str:
    """Helvetica only covers cp1252; map common symbols and replace the rest."""
    for src, dst in {"\u2192": "->", "\u2265": ">=", "\u2264": "<=", "\u2248": "~", "\u2011": "-"}.items():
        text = text.replace(src, dst)
    return text.encode("cp1252", "replace").decode("cp1252")


def _inline(text: str) -> str:
    text = escape(_clean(text))
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    return re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"<i>\1</i>", text)


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()["Normal"]
    return {
        "body": ParagraphStyle("body", parent=base, fontName="Helvetica", fontSize=10, leading=14.5,
                               spaceAfter=6, alignment=TA_LEFT),
        "h1": ParagraphStyle("h1", parent=base, fontName="Helvetica-Bold", fontSize=17, leading=21,
                             textColor=NAVY, spaceBefore=10, spaceAfter=8),
        "h2": ParagraphStyle("h2", parent=base, fontName="Helvetica-Bold", fontSize=13, leading=17,
                             textColor=ACCENT, spaceBefore=12, spaceAfter=5),
        "h3": ParagraphStyle("h3", parent=base, fontName="Helvetica-Bold", fontSize=11, leading=15,
                             textColor=NAVY, spaceBefore=8, spaceAfter=3),
        "bullet": ParagraphStyle("bullet", parent=base, fontSize=10, leading=14, leftIndent=16,
                                 bulletIndent=4, spaceAfter=3),
        "cell": ParagraphStyle("cell", parent=base, fontSize=8.5, leading=11),
        "head": ParagraphStyle("head", parent=base, fontName="Helvetica-Bold", fontSize=8.5,
                               leading=11, textColor=colors.white),
        "b_title": ParagraphStyle("b_title", parent=base, fontName="Helvetica-Bold", fontSize=22,
                                  leading=27, textColor=colors.white),
        "b_meta": ParagraphStyle("b_meta", parent=base, fontSize=9, leading=13,
                                 textColor=colors.HexColor("#D6E4F5")),
    }


def _grid(rows: list[list[str]], st: dict, width: float) -> Table:
    n = max(len(r) for r in rows)
    rows = [r + [""] * (n - len(r)) for r in rows]
    data = [[Paragraph(_inline(c), st["head" if i == 0 else "cell"]) for c in r] for i, r in enumerate(rows)]
    table = Table(data, colWidths=[width / n] * n, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ZEBRA]),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#B8C4D6")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return table


def _md_table(lines: list[str], st: dict, width: float) -> Table:
    rows = [[c.strip() for c in ln.strip().strip("|").split("|")] for ln in lines]
    rows = [r for r in rows if not all(re.fullmatch(r":?-+:?", c) for c in r if c)]
    return _grid(rows, st, width)


def markdown_to_flowables(md: str, st: dict, width: float) -> list:
    flow, para, lines, i = [], [], md.splitlines(), 0

    def flush():
        if para:
            flow.append(Paragraph(_inline(" ".join(para)), st["body"]))
            para.clear()

    while i < len(lines):
        s = lines[i].strip()
        if s.startswith("|"):
            flush()
            block = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                block.append(lines[i])
                i += 1
            flow += [_md_table(block, st, width), Spacer(1, 8)]
            continue
        if not s or re.fullmatch(r"-{3,}", s):
            flush()
        elif s.startswith("### "):
            flush(); flow.append(Paragraph(_inline(s[4:]), st["h3"]))
        elif s.startswith("## "):
            flush(); flow.append(Paragraph(_inline(s[3:]), st["h2"]))
        elif s.startswith("# "):
            flush(); flow.append(Paragraph(_inline(s[2:]), st["h1"]))
        elif re.match(r"^[-*] ", s):
            flush(); flow.append(Paragraph(_inline(s[2:]), st["bullet"], bulletText="\u2022"))
        elif re.match(r"^\d+\. ", s):
            flush()
            num, rest = s.split(". ", 1)
            flow.append(Paragraph(_inline(rest), st["bullet"], bulletText=f"{num}."))
        else:
            para.append(s)
        i += 1
    flush()
    return flow


def _running_header(c: canvas.Canvas, doc):
    width, height = A4
    c.saveState()
    c.setFont("Helvetica", 7.5)
    c.setFillColor(colors.grey)
    c.drawString(2 * cm, height - 1.2 * cm, _clean(doc.title))
    c.setStrokeColor(ACCENT)
    c.line(2 * cm, height - 1.4 * cm, width - 2 * cm, height - 1.4 * cm)
    c.restoreState()


def build_pdf(markdown: str, output_path: str | Path, title: str, query: str,
              summary_df: pd.DataFrame | None = None) -> Path:
    """Compile the writer's Markdown (+ optional Pandas summary grid) into an A4 PDF."""
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(
        str(output_path), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
        topMargin=2.2 * cm, bottomMargin=2.3 * cm, title=_clean(title),
        author="Multi-Agent Market Research Crew", subject=_clean(query),
    )
    st = _styles()
    meta = (f"Query: {escape(_clean(query))}<br/>Generated: {datetime.now():%Y-%m-%d %H:%M}"
            f"<br/>Pipeline: CrewAI hierarchical process (Researcher, Analyst, Writer)")
    banner = Table([[Paragraph(escape(_clean(title)), st["b_title"])], [Paragraph(meta, st["b_meta"])]],
                   colWidths=[doc.width])
    banner.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), NAVY), ("LINEBELOW", (0, -1), (-1, -1), 4, ACCENT),
        ("LEFTPADDING", (0, 0), (-1, -1), 14), ("TOPPADDING", (0, 0), (-1, 0), 14),
        ("BOTTOMPADDING", (0, -1), (-1, -1), 12),
    ]))
    story = [banner, Spacer(1, 14)] + markdown_to_flowables(markdown, st, doc.width)

    if summary_df is not None and not summary_df.empty:
        header = ["Statistic"] + [str(c) for c in summary_df.columns]
        rows = [header] + [[str(idx)] + [f"{v:,.2f}" for v in row] for idx, row in summary_df.iterrows()]
        story.append(KeepTogether([
            Paragraph("Statistical Summary (Pandas)", st["h2"]),
            Paragraph("Descriptive statistics computed from the collected metrics dataset.", st["body"]),
            _grid(rows, st, doc.width),
        ]))
    doc.build(story, onLaterPages=_running_header, canvasmaker=NumberedCanvas)
    return output_path
